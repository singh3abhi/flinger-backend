import { createZodDto } from 'nestjs-zod';
import { z } from 'zod';
import { LIMITS } from '@/common/limits';
import { memberSummarySchema } from '@/modules/matching';

export const messageSchema = z.object({
  id: z.uuid(),
  conversationId: z.uuid(),
  /** Null when the sender has deleted their account. */
  senderId: z.uuid().nullable(),
  body: z.string().max(LIMITS.messageMaxLength),
  clientMsgId: z.uuid(),
  createdAt: z.iso.datetime(),
});
export class MessageDto extends createZodDto(messageSchema) {}
export type MessageView = z.infer<typeof messageSchema>;

export const conversationSchema = z.object({
  /** Same as the match id. */
  id: z.uuid(),
  member: memberSummarySchema,
  matchedAt: z.iso.datetime(),
  lastMessage: z
    .object({
      id: z.uuid(),
      body: z.string().max(LIMITS.messageMaxLength),
      fromMe: z.boolean(),
      createdAt: z.iso.datetime(),
    })
    .nullable(),
  unreadCount: z.number().int(),
});
export const conversationListSchema = z.object({
  items: z.array(conversationSchema),
  nextCursor: z.string().max(200).nullable(),
  /** Conversations with unread messages (for the tab badge). */
  unreadConversations: z.number().int(),
});
export class ConversationListDto extends createZodDto(conversationListSchema) {}

export const messagePageQuerySchema = z
  .object({
    /** Older messages than this id (scrolling up). */
    before: z.uuid().optional(),
    /** Messages since this id (gap-fill after reconnect). May repeat a few; drop duplicates by id. */
    after: z.uuid().optional(),
    limit: z.coerce.number().int().min(1).max(100).default(30),
  })
  .refine((q) => !(q.before && q.after), 'use before or after, not both');
export class MessagePageQueryDto extends createZodDto(messagePageQuerySchema) {}

export const messagePageSchema = z.object({
  /** Oldest first. */
  items: z.array(messageSchema),
  /** More older messages exist (when paging with `before` or the first page). */
  hasMore: z.boolean(),
});
export class MessagePageDto extends createZodDto(messagePageSchema) {}

export const sendMessageSchema = z.object({
  /** Generated by the app; resending the same id never duplicates the message. */
  clientMsgId: z.uuid(),
  body: z.string().trim().min(1).max(LIMITS.messageMaxLength),
});
export class SendMessageDto extends createZodDto(sendMessageSchema) {}

export const markReadSchema = z.object({ upToMessageId: z.uuid() });
export class MarkReadDto extends createZodDto(markReadSchema) {}

export const conversationIdParamSchema = z.object({ conversationId: z.uuid() });
export class ConversationIdParamDto extends createZodDto(conversationIdParamSchema) {}
